// One-off generator for src/data/countries.ts.
//
// Sources (download them first, then pass the file paths):
//   countries: https://raw.githubusercontent.com/mledoze/countries/master/countries.json  (ODbL)
//   population: https://api.worldbank.org/v2/country/all/indicator/SP.POP.TOTL?format=json&date=2023&per_page=400
//
// Usage: node scripts/build-countries.mjs <countries.json> <population.json>
import { readFileSync, writeFileSync } from 'node:fs'

const [countriesPath, popPath] = process.argv.slice(2)
if (!countriesPath || !popPath) {
  console.error('Usage: node scripts/build-countries.mjs <countries.json> <population.json>')
  process.exit(1)
}

const raw = JSON.parse(readFileSync(countriesPath, 'utf8'))
const [, popRows] = JSON.parse(readFileSync(popPath, 'utf8'))
const population = new Map(popRows.map((r) => [r.countryiso3code, r.value ?? 0]))

// mledoze uses "Americas"; split it into North and South America like a school atlas.
function continentOf(c) {
  if (c.region === 'Americas') return c.subregion === 'South America' ? 'South America' : 'North America'
  return c.region // Africa, Asia, Europe, Oceania
}

const countries = raw
  .filter((c) => c.unMember && c.capital?.length)
  .map((c) => ({
    code: c.cca2,
    name: c.name.common,
    capital: c.capital[0],
    continent: continentOf(c),
    population: population.get(c.cca3) ?? 0,
  }))
  .sort((a, b) => a.name.localeCompare(b.name))

const out = `// GENERATED by scripts/build-countries.mjs — do not edit by hand.
// Country data: mledoze/countries (ODbL). Population: World Bank, 2023.
import type { Country } from './types'

export const COUNTRIES: Country[] = ${JSON.stringify(countries, null, 2)}
`
writeFileSync(new URL('../src/data/countries.ts', import.meta.url), out)
console.log(`Wrote ${countries.length} countries`)
